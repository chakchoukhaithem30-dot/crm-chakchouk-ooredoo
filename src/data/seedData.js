import { toISODate } from '../utils/formatters.js';

function offsetDaysISO(daysOffset) {
  const d = new Date();
  d.setDate(d.getDate() + daysOffset);
  return toISODate(d);
}

function anniversaryFromOffset(daysOffset, yearsAgo) {
  const d = new Date();
  d.setDate(d.getDate() + daysOffset);
  d.setFullYear(d.getFullYear() - yearsAgo);
  return toISODate(d);
}

function monthDateISO(monthsAgo, day = 15) {
  const now = new Date();
  const d = new Date(now.getFullYear(), now.getMonth() - monthsAgo, day);
  if (d > now) return toISODate(now);
  return toISODate(d);
}

